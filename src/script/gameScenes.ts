/**
 * ゲーム画面の中で話すセリフ（会話パート以外）。セリフ編集で書き換えられる。
 * 行に演出（スポットライト・カードを配る など）が結びつく行には tag() で名前（id）を付ける。演出は番号ではなく名前で探すので、前後に行を足しても、演出はずれない。
 * 名前を付けた行は、セリフ編集で消したり並べ替えたりできない（文章は直せる）。
 * pos は会話の位置（bottom=下のボタンのすぐ上 / corner=右上に小さく / top=画面の上 / shop=Santazon を開いている間の左下）
 */

type Pos = NovelLine['pos']
const say =
  (speaker: string, character: string, defEmotion: Emotion = '真顔') =>
  (text: string, emotion: Emotion = defEmotion, pos?: Pos): NovelLine => ({ speaker, character, text, emotion, pos })
