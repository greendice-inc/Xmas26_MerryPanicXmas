/**
 * ゲーム画面の中で話すセリフ（会話パート以外）。セリフ編集で書き換えられる。
 * 行に演出（スポットライト・カードを配る など）が結びついている場面は、行の数を変えられない（scriptData の fixed）。
 * pos は会話の位置（bottom=下のボタンのすぐ上 / top=画面の上 / shop=Santazon を開いている間の左下）
 */

type Pos = NovelLine['pos']
const say =
  (speaker: string, character: string, defEmotion: Emotion = '真顔') =>
  (text: string, emotion: Emotion = defEmotion, pos?: Pos): NovelLine => ({ speaker, character, text, emotion, pos })
const elf = say('エルフ', 'Common')
const rin = say('リン', 'Stage1', '楽')
const km = say('カイ・メイ', 'Stage3')
const robin = say('ロビン', 'Stage4')
const kid = (who: 'amy' | 'jimmy' | 'tommy') => (text: string): NovelLine => ({
  speaker: ST2_KIDS[who].name,
  charSrc: ST2_KIDS[who].image,
  text,
})
const scene = (character: string, lines: NovelLine[]): NovelScene => ({ character, background: character, lines })

